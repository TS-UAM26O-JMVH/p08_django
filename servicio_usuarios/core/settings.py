# NOTA: gestion_usuarios no emite tokens (eso lo hace autentificacion / servicio_auth).
# Usa JWTTokenUserAuthentication (en vez de JWTAuthentication) para validar el JWT de
# forma stateless: verifica la firma con la llave pública y arma un TokenUser a partir
# de los claims del token, SIN consultar ninguna tabla auth_user local. Esto es seguro
# porque ninguna vista de gestion_usuarios usa request.user más allá de la autenticación.
